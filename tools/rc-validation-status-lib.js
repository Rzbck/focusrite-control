const fs = require('node:fs')

const ALLOWED_OUTCOMES = new Set(['SUCCESS', 'FAILED'])
const ALLOWED_STAGES = new Set([
	'preflight',
	'dependencies',
	'format',
	'lint',
	'manifest',
	'tests',
	'build',
	'complete',
])
const ALLOWED_CODES = new Set([
	'ok',
	'unexpected',
	'node-unavailable',
	'corepack-unavailable',
	'install-failed',
	'format-failed',
	'lint-failed',
	'manifest-failed',
	'tests-failed',
	'build-failed',
])

function parseStatusText(text) {
	const fields = new Map()
	for (const line of String(text || '')
		.replace(/^\uFEFF/, '')
		.split(/\r?\n/)) {
		const match = /^([a-z-]+)=([A-Za-z0-9-]+)$/.exec(line.trim())
		if (match) fields.set(match[1], match[2])
	}
	const status = {
		outcome: fields.get('outcome') || '',
		stage: fields.get('stage') || '',
		code: fields.get('code') || '',
	}
	if (!ALLOWED_OUTCOMES.has(status.outcome)) throw new Error('Invalid RC validation outcome')
	if (!ALLOWED_STAGES.has(status.stage)) throw new Error('Invalid RC validation stage')
	if (!ALLOWED_CODES.has(status.code)) throw new Error('Invalid RC validation code')
	if (status.outcome === 'SUCCESS' && (status.stage !== 'complete' || status.code !== 'ok'))
		throw new Error('Invalid RC success tuple')
	if (status.outcome === 'FAILED' && status.code === 'ok') throw new Error('Invalid RC failure tuple')
	return status
}

function readStatusFile(file) {
	try {
		return parseStatusText(fs.readFileSync(file, 'utf8'))
	} catch {
		return { outcome: 'FAILED', stage: 'preflight', code: 'unexpected' }
	}
}

function validatePublishedStatus(text) {
	const value = String(text || '')
	for (const marker of [
		'Sanitized Focusrite RC state-contract validation',
		'Outcome:',
		'Stage:',
		'Code:',
		'Hardware writes during validation: none',
	]) {
		if (!value.includes(marker)) throw new Error(`RC status missing marker: ${marker}`)
	}
	const forbidden = [
		/\b[A-Za-z]:\\/,
		/\\\\[^\\\s]+\\/,
		/\b(?:\d{1,3}\.){3}\d{1,3}\b/,
		/<\/?[A-Za-z][^>]*>/,
		/\bLength=[0-9A-Fa-f]{6}\b/,
		/\bclient-key\s*=/i,
		/\bhostname\s*=/i,
		/\bdevid\s*=/i,
		/\bserial(?:-number)?\s*[:=]/i,
	]
	for (const rx of forbidden) if (rx.test(value)) throw new Error(`RC status rejected by privacy rule: ${rx}`)
	return true
}

function buildPublishedStatus({ status, sourceBranch, sourceCommit, nodeVersion }) {
	if (sourceBranch !== 'rc/v0.1.13-state-contract') throw new Error('RC status publication refused from wrong branch')
	if (!/^[0-9a-f]{40}$/i.test(String(sourceCommit || ''))) throw new Error('Invalid RC source commit SHA')
	if (!/^v?22\.\d+\.\d+$/.test(String(nodeVersion || ''))) throw new Error('Invalid Node 22 metadata')
	if (!ALLOWED_OUTCOMES.has(status?.outcome) || !ALLOWED_STAGES.has(status?.stage) || !ALLOWED_CODES.has(status?.code))
		throw new Error('Invalid RC status object')
	const text = [
		'# Sanitized Focusrite RC state-contract validation',
		'',
		'> Generated by the local RC validation runner.',
		'> Raw command output, local paths, device/network identifiers and hardware state are not uploaded.',
		'',
		`Source branch: ${sourceBranch}`,
		`Source commit: ${sourceCommit}`,
		`Node: ${String(nodeVersion).replace(/^v/, '')}`,
		'',
		`Outcome: ${status.outcome}`,
		`Stage: ${status.stage}`,
		`Code: ${status.code}`,
		'',
		'Validation scope: dependencies + format + lint + manifest + Node tests + companion-module-build',
		'Hardware writes during validation: none',
		'GitHub Actions used: no',
		'',
	].join('\n')
	validatePublishedStatus(text)
	return text
}

module.exports = {
	ALLOWED_OUTCOMES,
	ALLOWED_STAGES,
	ALLOWED_CODES,
	parseStatusText,
	readStatusFile,
	validatePublishedStatus,
	buildPublishedStatus,
}
